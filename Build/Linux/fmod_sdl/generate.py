#!/usr/bin/env python3
"""Generates fmod_stubs.cpp from the FMOD 1.07 headers in fmod/include.

Every entry point of the C and C++ API that fmod_sdl.cpp does not implement is
defined here and fails with FMOD_ERR_UNSUPPORTED, so the engine links against
the whole API and gets a clear error from the parts that have no counterpart
(DSP plug-ins, recording, geometry). Re-run after implementing another function
in fmod_sdl.cpp or changing the FMOD headers.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
INC = os.path.join(HERE, '..', '..', 'fmod', 'include')

implemented = open(os.path.join(HERE, 'fmod_sdl.cpp')).read()
done_cpp = set(re.findall(r'F_API\s+(\w+::\w+)\s*\(', implemented))
done_c = set(re.findall(r'F_API\s+(FMOD_\w+)\s*\(', implemented))

def strip_defaults(args):
    out, depth, cur = [], 0, ''
    for ch in args:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur); cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return ', '.join(a.split('=')[0].strip() for a in out)

lines = ['// Generated by generate.py - do not edit. What fmod_sdl.cpp does not implement.',
         '#include "fmod.h"',
         '#include "fmod.hpp"',
         '',
         '#define NULL_RESULT FMOD_ERR_UNSUPPORTED',
         '',
         'extern "C" {']

c_re = re.compile(r'^FMOD_RESULT\s+F_API\s+(FMOD_\w+)\s*\((.*)\);')
for l in open(os.path.join(INC, 'fmod.h')):
    m = c_re.match(l.strip())
    if m and m.group(1) not in done_c:
        lines.append('FMOD_RESULT F_API %s(%s) { return NULL_RESULT; }' % (m.group(1), strip_defaults(m.group(2))))
lines += ['}', '', 'namespace FMOD', '{']

cls = None
cls_re = re.compile(r'^\s*class\s+(\w+)\s*(:.*)?$')
m_re = re.compile(r'^\s*FMOD_RESULT\s+F_API\s+(\w+)\s*\((.*)\);')
for l in open(os.path.join(INC, 'fmod.hpp')):
    c = cls_re.match(l)
    if c:
        cls = c.group(1)
        continue
    m = m_re.match(l)
    if m and cls and ('%s::%s' % (cls, m.group(1))) not in done_cpp:
        lines.append('    FMOD_RESULT F_API %s::%s(%s) { return NULL_RESULT; }' % (cls, m.group(1), strip_defaults(m.group(2))))
lines += ['}', '']

open(os.path.join(HERE, 'fmod_stubs.cpp'), 'w').write('\n'.join(lines))
